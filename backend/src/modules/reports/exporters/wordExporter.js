const {
  Document,
  Packer,
  Paragraph,
  TextRun,
  Table,
  TableRow,
  TableCell,
  WidthType,
  AlignmentType,
  HeadingLevel,
  BorderStyle,
} = require('docx');
const { formatLocalTimestamp } = require('../../../utils/dateUtil');

function createCell(text, isHeader = false, widthPercent = null, align = AlignmentType.LEFT) {
  return new TableCell({
    width: widthPercent ? { size: widthPercent, type: WidthType.PERCENTAGE } : undefined,
    shading: isHeader ? { fill: '1E3A8A' } : undefined,
    children: [
      new Paragraph({
        alignment: align,
        children: [
          new TextRun({
            text: String(text !== undefined && text !== null ? text : ''),
            bold: isHeader,
            color: isHeader ? 'FFFFFF' : '1F2937',
            size: 18, // 9pt
            font: 'Arial',
          }),
        ],
      }),
    ],
  });
}

/**
 * Generates an official Word (.docx) report buffer using docx
 */
async function generateWordReport(reportData, options = {}) {
  const { scope = 'staff', actorUser = {} } = options;
  const { summary, by_document_type = [], by_status = [], staff_workload = [], transactions = {} } = reportData;

  const fromFormatted = summary.from ? summary.from.slice(0, 10) : '';
  const toFormatted = summary.to ? summary.to.slice(0, 10) : '';
  const generatedAt = formatLocalTimestamp(new Date());

  const docChildren = [
    // Header
    new Paragraph({
      alignment: AlignmentType.CENTER,
      heading: HeadingLevel.HEADING_1,
      children: [
        new TextRun({
          text: 'QUICKFILE BARANGAY DOCUMENT MANAGEMENT SYSTEM',
          bold: true,
          color: '1E3A8A',
          size: 28,
        }),
      ],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [
        new TextRun({
          text: 'OFFICIAL TRANSACTION & REVENUE SUMMARY REPORT',
          bold: true,
          color: '4B5563',
          size: 22,
        }),
      ],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [
        new TextRun({
          text: `Period: ${fromFormatted} to ${toFormatted}  |  Generated: ${generatedAt}  |  Scope: ${scope === 'admin' ? 'Administrator (Full)' : 'Staff (General)'}`,
          color: '6B7280',
          size: 18,
        }),
      ],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [
        new TextRun({
          text: `Generated By: ${actorUser.full_name || 'Authorized Officer'} (${(actorUser.role || 'staff').toUpperCase()})`,
          color: '6B7280',
          size: 18,
        }),
      ],
      spacing: { after: 300 },
    }),

    // Section 1: Executive Summary
    new Paragraph({
      heading: HeadingLevel.HEADING_2,
      children: [new TextRun({ text: '1. Executive Summary', bold: true, color: '1E3A8A', size: 22 })],
      spacing: { before: 200, after: 100 },
    }),
    new Table({
      width: { size: 100, type: WidthType.PERCENTAGE },
      rows: [
        new TableRow({
          children: [
            createCell('Metric Indicator', true, 60),
            createCell('Summary Value', true, 40, AlignmentType.RIGHT),
          ],
        }),
        new TableRow({ children: [createCell('Total Requests Submitted'), createCell(summary.total_requests || 0, false, null, AlignmentType.RIGHT)] }),
        new TableRow({ children: [createCell('Total Requests Released'), createCell(summary.released_count || 0, false, null, AlignmentType.RIGHT)] }),
        new TableRow({ children: [createCell('Total Requests Rejected'), createCell(summary.rejected_count || 0, false, null, AlignmentType.RIGHT)] }),
        new TableRow({ children: [createCell('Total Collected Revenue'), createCell(`₱ ${(summary.total_revenue || 0).toFixed(2)}`, false, null, AlignmentType.RIGHT)] }),
        new TableRow({ children: [createCell('Fees Waived (Indigency / Exempt)'), createCell(`${summary.waived_count || 0} (₱ ${(summary.waived_amount || 0).toFixed(2)})`, false, null, AlignmentType.RIGHT)] }),
      ],
    }),

    // Section 2: Breakdown by Document Type
    new Paragraph({
      heading: HeadingLevel.HEADING_2,
      children: [new TextRun({ text: '2. Requests by Document Type', bold: true, color: '1E3A8A', size: 22 })],
      spacing: { before: 300, after: 100 },
    }),
    new Table({
      width: { size: 100, type: WidthType.PERCENTAGE },
      rows: [
        new TableRow({
          children: [
            createCell('Code', true, 15),
            createCell('Document Name', true, 40),
            createCell('Requests', true, 15, AlignmentType.RIGHT),
            createCell('Standard Fee', true, 15, AlignmentType.RIGHT),
            createCell('Revenue', true, 15, AlignmentType.RIGHT),
          ],
        }),
        ...by_document_type.map(
          (d) =>
            new TableRow({
              children: [
                createCell(d.code || 'N/A'),
                createCell(d.name || 'Unnamed Document'),
                createCell(d.count || 0, false, null, AlignmentType.RIGHT),
                createCell(`₱ ${(d.fee || 0).toFixed(2)}`, false, null, AlignmentType.RIGHT),
                createCell(`₱ ${(d.collected_revenue || 0).toFixed(2)}`, false, null, AlignmentType.RIGHT),
              ],
            })
        ),
      ],
    }),

    // Section 3: Status Breakdown
    new Paragraph({
      heading: HeadingLevel.HEADING_2,
      children: [new TextRun({ text: '3. Requests by Processing Status', bold: true, color: '1E3A8A', size: 22 })],
      spacing: { before: 300, after: 100 },
    }),
    new Table({
      width: { size: 100, type: WidthType.PERCENTAGE },
      rows: [
        new TableRow({
          children: [
            createCell('Processing Status', true, 60),
            createCell('Total Requests', true, 40, AlignmentType.RIGHT),
          ],
        }),
        ...by_status.map(
          (s) =>
            new TableRow({
              children: [
                createCell((s.status || '').toUpperCase().replace(/_/g, ' ')),
                createCell(s.count || 0, false, null, AlignmentType.RIGHT),
              ],
            })
        ),
      ],
    }),
  ];

  // Section 4: Staff Workload (Admin scope only)
  if (scope === 'admin' && Array.isArray(staff_workload) && staff_workload.length > 0) {
    docChildren.push(
      new Paragraph({
        heading: HeadingLevel.HEADING_2,
        children: [new TextRun({ text: '4. Staff Workload & Performance', bold: true, color: '1E3A8A', size: 22 })],
        spacing: { before: 300, after: 100 },
      }),
      new Table({
        width: { size: 100, type: WidthType.PERCENTAGE },
        rows: [
          new TableRow({
            children: [
              createCell('Staff Officer Name', true, 50),
              createCell('Designation / Department', true, 30),
              createCell('Processed Records', true, 20, AlignmentType.RIGHT),
            ],
          }),
          ...staff_workload.map(
            (w) =>
              new TableRow({
                children: [
                  createCell(w.staff_name || 'Staff Member'),
                  createCell(w.position || 'Barangay Staff'),
                  createCell(w.processed_count || 0, false, null, AlignmentType.RIGHT),
                ],
              })
          ),
        ],
      })
    );
  }

  // Section 5: Transactions List (Sample up to 100 for Word document)
  const txItems = transactions.items || [];
  if (txItems.length > 0) {
    const sectionNum = scope === 'admin' && staff_workload.length > 0 ? '5' : '4';
    docChildren.push(
      new Paragraph({
        heading: HeadingLevel.HEADING_2,
        children: [
          new TextRun({
            text: `${sectionNum}. Detailed Transactions (${Math.min(txItems.length, 50)} of ${transactions.total || txItems.length} records)`,
            bold: true,
            color: '1E3A8A',
            size: 22,
          }),
        ],
        spacing: { before: 300, after: 100 },
      })
    );

    if (transactions.truncated) {
      docChildren.push(
        new Paragraph({
          children: [
            new TextRun({
              text: `* Notice: Transaction export capped at ${transactions.max_rows || 5000} records due to system export limits.`,
              italics: true,
              color: 'B91C1C',
              size: 18,
            }),
          ],
          spacing: { after: 100 },
        })
      );
    }

    docChildren.push(
      new Table({
        width: { size: 100, type: WidthType.PERCENTAGE },
        rows: [
          new TableRow({
            children: [
              createCell('Tracking #', true, 20),
              createCell('Citizen Name', true, 25),
              createCell('Document', true, 20),
              createCell('Status', true, 15),
              createCell('Fee', true, 10, AlignmentType.RIGHT),
              createCell('Date', true, 10),
            ],
          }),
          ...txItems.slice(0, 50).map(
            (t) =>
              new TableRow({
                children: [
                  createCell(t.tracking_number || ''),
                  createCell(t.citizen_name || ''),
                  createCell(t.document_type_name || ''),
                  createCell((t.status || '').toUpperCase().replace(/_/g, ' ')),
                  createCell(`₱ ${(t.fee || 0).toFixed(2)}`, false, null, AlignmentType.RIGHT),
                  createCell(t.created_at ? new Date(t.created_at).toISOString().slice(0, 10) : ''),
                ],
              })
          ),
        ],
      })
    );
  }

  const doc = new Document({
    sections: [
      {
        properties: {},
        children: docChildren,
      },
    ],
  });

  return await Packer.toBuffer(doc);
}

module.exports = {
  generateWordReport,
};
