const ExcelJS = require('exceljs');
const { config } = require('../../../config');
const { formatLocalTimestamp, formatLocalDate } = require('../../../utils/dateUtil');

/**
 * Formula Injection Neutralization
 * If any cell string begins with =, +, -, @, \t, or \r, prepend a single quote (')
 */
function sanitizeFormula(val) {
  if (val === null || val === undefined) return '';
  if (typeof val !== 'string') return val;
  if (/^[=+\-@\t\r]/.test(val)) {
    return `'${val}`;
  }
  return val;
}

/**
 * Auto-adjusts column widths based on maximum length of cell values
 */
function autoFitColumns(worksheet) {
  worksheet.columns.forEach((column) => {
    let maxLen = 14;
    column.eachCell({ includeEmpty: true }, (cell) => {
      const len = cell.value ? String(cell.value).length : 0;
      if (len > maxLen) {
        maxLen = Math.min(len + 3, 50);
      }
    });
    column.width = maxLen;
  });
}

/**
 * Configures print header and footer on a worksheet
 */
function applyHeaderFooter(worksheet, sheetTitle, barangayName) {
  worksheet.headerFooter.oddHeader = `&L${barangayName}&C${sheetTitle}&R&D`;
  worksheet.headerFooter.oddFooter = `&LQuickFile Document Management System&RPage &P of &N`;
}

/**
 * Generates an official Excel (.xlsx) report workbook using exceljs
 * Produces separate sheets: Summary, By Document Type, By Status, Staff Workload (admin only), Transactions
 */
async function generateExcelReport(reportData, options = {}) {
  const { scope = 'staff', actorUser = {} } = options;
  const { summary, by_document_type = [], by_status = [], staff_workload = [], transactions = {} } = reportData;

  const barangayName = config.jurisdiction.barangayName() || 'Barangay Local Government Unit';
  const fromFormatted = summary.from || '';
  const toFormatted = summary.to || '';
  const generatedAt = formatLocalTimestamp(new Date());

  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'QuickFile Barangay Portal';
  workbook.created = new Date();

  // ============================================================================
  // SHEET 1: Summary
  // ============================================================================
  const summarySheet = workbook.addWorksheet('Summary');
  applyHeaderFooter(summarySheet, 'Executive Summary', barangayName);

  summarySheet.addRow([sanitizeFormula(barangayName.toUpperCase())]);
  summarySheet.addRow([sanitizeFormula('OFFICIAL DOCUMENT TRANSACTIONS & REVENUE SUMMARY')]);
  summarySheet.addRow([]);
  summarySheet.addRow(['Reporting Period:', sanitizeFormula(`${fromFormatted} to ${toFormatted}`)]);
  summarySheet.addRow(['Generated At:', sanitizeFormula(generatedAt)]);
  summarySheet.addRow(['Report Scope:', sanitizeFormula(scope === 'admin' ? 'Administrator (Full System)' : 'Staff (Operations)')]);
  summarySheet.addRow(['Generated By:', sanitizeFormula(`${actorUser.full_name || 'Staff'} (${(actorUser.role || 'staff').toUpperCase()})`)]);
  summarySheet.addRow([]);

  // Freeze header row above KPI table
  const kpiHeaderRow = summarySheet.addRow(['Executive Summary Metric', 'Value']);
  kpiHeaderRow.font = { bold: true };
  summarySheet.views = [{ state: 'frozen', ySplit: 9 }];

  const kpiRows = [
    ['Total Requests Submitted', summary.total_requests || 0],
    ['Total Requests Released', summary.released_count || 0],
    ['Total Requests Rejected', summary.rejected_count || 0],
    ['Total Collected Revenue (PHP)', summary.total_revenue || 0, true],
    ['Fees Waived Count', summary.waived_count || 0],
    ['Total Fees Waived (PHP)', summary.waived_amount || 0, true],
  ];

  for (const item of kpiRows) {
    const row = summarySheet.addRow([item[0], item[1]]);
    if (item[2]) {
      const cell = row.getCell(2);
      cell.numFmt = '#,##0.00';
    }
  }

  autoFitColumns(summarySheet);

  // ============================================================================
  // SHEET 2: By Document Type
  // ============================================================================
  const docSheet = workbook.addWorksheet('By Document Type');
  applyHeaderFooter(docSheet, 'Requests By Document Type', barangayName);

  docSheet.addRow([sanitizeFormula(barangayName.toUpperCase())]);
  docSheet.addRow([sanitizeFormula(`REQUESTS BY DOCUMENT TYPE (${fromFormatted} to ${toFormatted})`)]);
  docSheet.addRow([]);

  const docHeaderRow = docSheet.addRow([
    'Document Code',
    'Document Name',
    'Requests Count',
    'Unit Fee (PHP)',
    'Collected Revenue (PHP)',
  ]);
  docHeaderRow.font = { bold: true };
  docSheet.views = [{ state: 'frozen', ySplit: 4 }];

  for (const d of by_document_type) {
    const row = docSheet.addRow([
      sanitizeFormula(d.document_code || 'N/A'),
      sanitizeFormula(d.document_name || 'Unnamed Document'),
      d.count || 0,
      d.unit_fee || 0,
      d.collected_amount || 0,
    ]);
    row.getCell(4).numFmt = '#,##0.00';
    row.getCell(5).numFmt = '#,##0.00';
  }

  autoFitColumns(docSheet);

  // ============================================================================
  // SHEET 3: By Status
  // ============================================================================
  const statusSheet = workbook.addWorksheet('By Status');
  applyHeaderFooter(statusSheet, 'Requests By Status', barangayName);

  statusSheet.addRow([sanitizeFormula(barangayName.toUpperCase())]);
  statusSheet.addRow([sanitizeFormula(`REQUESTS BY PROCESSING STATUS (${fromFormatted} to ${toFormatted})`)]);
  statusSheet.addRow([]);

  const statusHeaderRow = statusSheet.addRow(['Processing Status', 'Total Requests']);
  statusHeaderRow.font = { bold: true };
  statusSheet.views = [{ state: 'frozen', ySplit: 4 }];

  for (const s of by_status) {
    statusSheet.addRow([
      sanitizeFormula((s.status || '').toUpperCase().replace(/_/g, ' ')),
      s.count || 0,
    ]);
  }

  autoFitColumns(statusSheet);

  // ============================================================================
  // SHEET 4: Staff Workload (Admin scope only)
  // ============================================================================
  if (scope === 'admin') {
    const staffSheet = workbook.addWorksheet('Staff Workload');
    applyHeaderFooter(staffSheet, 'Staff Processing Workload', barangayName);

    staffSheet.addRow([sanitizeFormula(barangayName.toUpperCase())]);
    staffSheet.addRow([sanitizeFormula(`STAFF WORKLOAD & ACTIVITY AUDIT (${fromFormatted} to ${toFormatted})`)]);
    staffSheet.addRow([]);

    const staffHeaderRow = staffSheet.addRow([
      'Staff Officer Name',
      'Role',
      'Actions Breakdown',
      'Total Actions',
    ]);
    staffHeaderRow.font = { bold: true };
    staffSheet.views = [{ state: 'frozen', ySplit: 4 }];

    for (const w of staff_workload) {
      const breakdownText = Object.entries(w.per_status || {})
        .map(([st, cnt]) => `${st.replace(/_/g, ' ')}: ${cnt}`)
        .join(', ');
      staffSheet.addRow([
        sanitizeFormula(w.staff_name || 'Staff Member'),
        sanitizeFormula((w.role || 'staff').toUpperCase()),
        sanitizeFormula(breakdownText || 'None'),
        w.total_actions || 0,
      ]);
    }

    autoFitColumns(staffSheet);
  }

  // ============================================================================
  // SHEET 5: Transactions
  // ============================================================================
  const txSheet = workbook.addWorksheet('Transactions');
  applyHeaderFooter(txSheet, 'Document Transactions List', barangayName);

  const txItems = transactions.items || [];
  const isTruncated = transactions.truncated;

  txSheet.addRow([sanitizeFormula(barangayName.toUpperCase())]);
  txSheet.addRow([
    sanitizeFormula(
      isTruncated
        ? `DETAILED TRANSACTIONS (Showing first ${txItems.length} of ${transactions.total})`
        : `DETAILED TRANSACTIONS (${txItems.length} records)`
    ),
  ]);

  if (isTruncated) {
    txSheet.addRow([
      sanitizeFormula(`* Showing first ${txItems.length} of ${transactions.total} records due to system export limits.`),
    ]);
  } else {
    txSheet.addRow([]);
  }

  const txHeaderRow = txSheet.addRow([
    'Tracking Number',
    'Applicant Name',
    'Document Name',
    'Document Code',
    'Status',
    'Fee (PHP)',
    'Payment Status',
    'Payment Reference',
    'Waiver Reason',
    'Requested Date',
    'Released Date',
  ]);
  txHeaderRow.font = { bold: true };
  txSheet.views = [{ state: 'frozen', ySplit: 4 }];

  for (const t of txItems) {
    const reqDate = t.created_at ? new Date(t.created_at) : null;
    const relDate = t.released_at ? new Date(t.released_at) : null;

    const row = txSheet.addRow([
      sanitizeFormula(t.tracking_number || ''),
      sanitizeFormula(t.applicant_name || ''),
      sanitizeFormula(t.document_name || ''),
      sanitizeFormula(t.document_code || ''),
      sanitizeFormula((t.status || '').toUpperCase().replace(/_/g, ' ')),
      t.fee !== undefined ? Number(t.fee) : 0,
      sanitizeFormula((t.payment_status || '').toUpperCase()),
      sanitizeFormula(t.payment_reference || ''),
      sanitizeFormula(t.waiver_reason || ''),
      reqDate,
      relDate,
    ]);

    row.getCell(6).numFmt = '#,##0.00';
    if (reqDate) {
      row.getCell(10).numFmt = 'yyyy-mm-dd';
    }
    if (relDate) {
      row.getCell(11).numFmt = 'yyyy-mm-dd';
    }
  }

  autoFitColumns(txSheet);

  return await workbook.xlsx.writeBuffer();
}

module.exports = {
  generateExcelReport,
  sanitizeFormula,
};