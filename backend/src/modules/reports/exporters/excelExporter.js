const ExcelJS = require('exceljs');
const { formatLocalTimestamp } = require('../../../utils/dateUtil');

/**
 * Formula Injection Neutralization
 * If any cell string begins with =, +, -, @, \t, or \r, prepend a single quote (')
 */
function sanitizeFormula(val) {
  if (val === null || val === undefined) return '';
  if (typeof val !== 'string') return val;
  if (/^[=+\-@\t\r]/.test(val)) {
    return `'${val}`;
  }
  return val;
}

/**
 * Auto-adjusts column widths based on maximum length of cell values
 */
function autoFitColumns(worksheet) {
  worksheet.columns.forEach((column) => {
    let maxLen = 12;
    column.eachCell({ includeEmpty: true }, (cell) => {
      const len = cell.value ? String(cell.value).length : 0;
      if (len > maxLen) {
        maxLen = Math.min(len + 3, 50);
      }
    });
    column.width = maxLen;
  });
}

/**
 * Generates an official Excel (.xlsx) report buffer using exceljs
 */
async function generateExcelReport(reportData, options = {}) {
  const { scope = 'staff', actorUser = {} } = options;
  const { summary, by_document_type = [], by_status = [], staff_workload = [], transactions = {} } = reportData;

  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'QuickFile Barangay Portal';
  workbook.created = new Date();

  // ============================================================================
  // SHEET 1: Summary & Analytics
  // ============================================================================
  const summarySheet = workbook.addWorksheet('Summary');

  // Title Block
  summarySheet.addRow([sanitizeFormula('QUICKFILE BARANGAY DOCUMENT MANAGEMENT SYSTEM')]);
  summarySheet.addRow([sanitizeFormula('OFFICIAL TRANSACTION & REVENUE SUMMARY REPORT')]);
  summarySheet.addRow([]);

  const fromFormatted = summary.from ? summary.from.slice(0, 10) : '';
  const toFormatted = summary.to ? summary.to.slice(0, 10) : '';
  const generatedAt = formatLocalTimestamp(new Date());

  summarySheet.addRow(['Reporting Period:', sanitizeFormula(`${fromFormatted} to ${toFormatted}`)]);
  summarySheet.addRow(['Generated At:', sanitizeFormula(generatedAt)]);
  summarySheet.addRow(['Report Scope:', sanitizeFormula(scope === 'admin' ? 'Administrator (Full Scope)' : 'Staff (General Scope)')]);
  summarySheet.addRow(['Generated By:', sanitizeFormula(`${actorUser.full_name || 'Staff'} (${(actorUser.role || 'staff').toUpperCase()})`)]);
  summarySheet.addRow([]);

  // Section 1: KPI Summary
  const kpiHeaderRow = summarySheet.addRow(['Executive Summary Metric', 'Value']);
  kpiHeaderRow.font = { bold: true };

  summarySheet.addRow(['Total Requests Submitted', summary.total_requests || 0]);
  summarySheet.addRow(['Total Requests Released', summary.released_count || 0]);
  summarySheet.addRow(['Total Requests Rejected', summary.rejected_count || 0]);
  summarySheet.addRow(['Total Collected Revenue (PHP)', summary.total_revenue || 0]);
  summarySheet.addRow(['Fees Waived Count', summary.waived_count || 0]);
  summarySheet.addRow(['Total Fees Waived (PHP)', summary.waived_amount || 0]);
  summarySheet.addRow([]);

  // Section 2: Breakdown by Document Type
  const docHeaderRow = summarySheet.addRow([
    'Document Code',
    'Document Type Name',
    'Total Requests',
    'Standard Fee (PHP)',
    'Collected Revenue (PHP)',
  ]);
  docHeaderRow.font = { bold: true };

  for (const d of by_document_type) {
    summarySheet.addRow([
      sanitizeFormula(d.code || 'N/A'),
      sanitizeFormula(d.name || 'Unnamed Document'),
      d.count || 0,
      d.fee || 0,
      d.collected_revenue || 0,
    ]);
  }
  summarySheet.addRow([]);

  // Section 3: Status Breakdown
  const statusHeaderRow = summarySheet.addRow(['Processing Status', 'Total Requests']);
  statusHeaderRow.font = { bold: true };

  for (const s of by_status) {
    summarySheet.addRow([
      sanitizeFormula((s.status || '').toUpperCase().replace(/_/g, ' ')),
      s.count || 0,
    ]);
  }
  summarySheet.addRow([]);

  // Section 4: Staff Workload (Admin scope only)
  if (scope === 'admin' && Array.isArray(staff_workload) && staff_workload.length > 0) {
    const staffHeaderRow = summarySheet.addRow(['Staff Officer Name', 'Designation / Department', 'Processed Requests']);
    staffHeaderRow.font = { bold: true };

    for (const w of staff_workload) {
      summarySheet.addRow([
        sanitizeFormula(w.staff_name || 'Staff Member'),
        sanitizeFormula(w.position || 'Staff'),
        w.processed_count || 0,
      ]);
    }
  }

  autoFitColumns(summarySheet);

  // ============================================================================
  // SHEET 2: Transactions
  // ============================================================================
  const txSheet = workbook.addWorksheet('Transactions');

  if (transactions.truncated) {
    txSheet.addRow([
      sanitizeFormula(`* Notice: Transaction rows capped at ${transactions.max_rows || 5000} records due to system export limits.`),
    ]);
    txSheet.addRow([]);
  }

  const txHeaderRow = txSheet.addRow([
    'Tracking Number',
    'Citizen Full Name',
    'Document Type',
    'Status',
    'Fee (PHP)',
    'Payment Status',
    'Payment Reference',
    'Waiver Reason',
    'Request Date',
    'Released Date',
  ]);
  txHeaderRow.font = { bold: true };

  const txItems = transactions.items || [];
  for (const t of txItems) {
    txSheet.addRow([
      sanitizeFormula(t.tracking_number || ''),
      sanitizeFormula(t.citizen_name || ''),
      sanitizeFormula(t.document_type_name || ''),
      sanitizeFormula((t.status || '').toUpperCase().replace(/_/g, ' ')),
      t.fee !== undefined ? t.fee : 0,
      sanitizeFormula((t.payment_status || '').toUpperCase()),
      sanitizeFormula(t.payment_reference || ''),
      sanitizeFormula(t.waiver_reason || ''),
      sanitizeFormula(t.created_at ? new Date(t.created_at).toISOString().slice(0, 10) : ''),
      sanitizeFormula(t.released_at ? new Date(t.released_at).toISOString().slice(0, 10) : ''),
    ]);
  }

  autoFitColumns(txSheet);

  return await workbook.xlsx.writeBuffer();
}

module.exports = {
  generateExcelReport,
  sanitizeFormula,
};
