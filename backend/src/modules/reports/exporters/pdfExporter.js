const path = require('path');
const pdfmake = require('pdfmake');
const { formatLocalTimestamp } = require('../../../utils/dateUtil');

// Initialize Roboto fonts from pdfmake package
pdfmake.fonts = {
  Roboto: {
    normal: path.resolve(__dirname, '../../../../node_modules/pdfmake/fonts/Roboto/Roboto-Regular.ttf'),
    bold: path.resolve(__dirname, '../../../../node_modules/pdfmake/fonts/Roboto/Roboto-Medium.ttf'),
    italics: path.resolve(__dirname, '../../../../node_modules/pdfmake/fonts/Roboto/Roboto-Italic.ttf'),
    bolditalics: path.resolve(__dirname, '../../../../node_modules/pdfmake/fonts/Roboto/Roboto-MediumItalic.ttf'),
  },
};

pdfmake.setUrlAccessPolicy(() => false);
pdfmake.setLocalAccessPolicy(() => true);

/**
 * Generates an official PDF report buffer using pdfmake
 */
async function generatePdfReport(reportData, options = {}) {
  const { scope = 'staff', actorUser = {} } = options;
  const { summary, by_document_type = [], by_status = [], staff_workload = [], transactions = {} } = reportData;

  const fromFormatted = summary.from ? summary.from.slice(0, 10) : '';
  const toFormatted = summary.to ? summary.to.slice(0, 10) : '';
  const generatedAt = formatLocalTimestamp(new Date());

  // 1. Header & Metadata
  const docDefinition = {
    pageSize: 'A4',
    pageOrientation: 'portrait',
    pageMargins: [40, 40, 40, 40],
    defaultStyle: {
      font: 'Roboto',
      fontSize: 9,
      color: '#1f2937',
    },
    styles: {
      headerTitle: { fontSize: 16, bold: true, color: '#1e3a8a', alignment: 'center' },
      headerSubtitle: { fontSize: 11, bold: true, color: '#4b5563', alignment: 'center', margin: [0, 2, 0, 8] },
      metaText: { fontSize: 8, color: '#6b7280', alignment: 'center' },
      sectionHeading: { fontSize: 11, bold: true, color: '#1e3a8a', margin: [0, 14, 0, 6] },
      tableHeader: { fontSize: 8, bold: true, color: '#ffffff', fillColor: '#1e3a8a' },
      tableCell: { fontSize: 8 },
      kpiValue: { fontSize: 13, bold: true, color: '#1e3a8a', alignment: 'center' },
      kpiLabel: { fontSize: 8, color: '#4b5563', alignment: 'center' },
      warningText: { fontSize: 8, italics: true, color: '#b91c1c', margin: [0, 4, 0, 4] },
    },
    content: [
      { text: 'QUICKFILE BARANGAY DOCUMENT MANAGEMENT SYSTEM', style: 'headerTitle' },
      { text: 'OFFICIAL TRANSACTION & REVENUE SUMMARY REPORT', style: 'headerSubtitle' },
      {
        text: `Reporting Period: ${fromFormatted} to ${toFormatted}  |  Generated: ${generatedAt}  |  Scope: ${scope === 'admin' ? 'Administrator (Full)' : 'Staff (General)'}`,
        style: 'metaText',
      },
      {
        text: `Generated By: ${actorUser.full_name || 'Authorized Officer'} (${(actorUser.role || 'staff').toUpperCase()})`,
        style: 'metaText',
        margin: [0, 2, 0, 10],
      },
      { canvas: [{ type: 'line', x1: 0, y1: 0, x2: 515, y2: 0, lineWidth: 1, lineColor: '#cbd5e1' }] },

      // 2. Summary KPIs
      { text: 'Executive Summary', style: 'sectionHeading' },
      {
        table: {
          widths: ['*', '*', '*', '*', '*'],
          body: [
            [
              { text: `${summary.total_requests || 0}`, style: 'kpiValue' },
              { text: `${summary.released_count || 0}`, style: 'kpiValue' },
              { text: `${summary.rejected_count || 0}`, style: 'kpiValue' },
              { text: `₱ ${(summary.total_revenue || 0).toLocaleString('en-PH', { minimumFractionDigits: 2 })}`, style: 'kpiValue' },
              { text: `${summary.waived_count || 0} (₱ ${(summary.waived_amount || 0).toFixed(2)})`, style: 'kpiValue' },
            ],
            [
              { text: 'Total Requests', style: 'kpiLabel' },
              { text: 'Released', style: 'kpiLabel' },
              { text: 'Rejected', style: 'kpiLabel' },
              { text: 'Collected Revenue', style: 'kpiLabel' },
              { text: 'Fees Waived', style: 'kpiLabel' },
            ],
          ],
        },
        layout: 'lightHorizontalLines',
      },

      // 3. Breakdown by Document Type
      { text: 'Requests by Document Type', style: 'sectionHeading' },
      {
        table: {
          headerRows: 1,
          widths: [50, '*', 60, 70, 75],
          body: [
            [
              { text: 'Code', style: 'tableHeader' },
              { text: 'Document Name', style: 'tableHeader' },
              { text: 'Requests', style: 'tableHeader', alignment: 'right' },
              { text: 'Standard Fee', style: 'tableHeader', alignment: 'right' },
              { text: 'Revenue', style: 'tableHeader', alignment: 'right' },
            ],
            ...by_document_type.map((d) => [
              { text: d.code || 'N/A', style: 'tableCell' },
              { text: d.name || 'Unnamed Document', style: 'tableCell' },
              { text: `${d.count || 0}`, style: 'tableCell', alignment: 'right' },
              { text: `₱ ${(d.fee || 0).toFixed(2)}`, style: 'tableCell', alignment: 'right' },
              { text: `₱ ${(d.collected_revenue || 0).toFixed(2)}`, style: 'tableCell', alignment: 'right' },
            ]),
          ],
        },
        layout: 'grid',
      },

      // 4. Breakdown by Status
      { text: 'Requests by Processing Status', style: 'sectionHeading' },
      {
        table: {
          headerRows: 1,
          widths: ['*', 100],
          body: [
            [
              { text: 'Status', style: 'tableHeader' },
              { text: 'Count', style: 'tableHeader', alignment: 'right' },
            ],
            ...by_status.map((s) => [
              { text: (s.status || '').toUpperCase().replace(/_/g, ' '), style: 'tableCell' },
              { text: `${s.count || 0}`, style: 'tableCell', alignment: 'right' },
            ]),
          ],
        },
        layout: 'grid',
      },
    ],
  };

  // 5. Staff Workload (Admin scope only)
  if (scope === 'admin' && Array.isArray(staff_workload) && staff_workload.length > 0) {
    docDefinition.content.push(
      { text: 'Staff Processing Workload', style: 'sectionHeading' },
      {
        table: {
          headerRows: 1,
          widths: ['*', 120, 80],
          body: [
            [
              { text: 'Staff Member Name', style: 'tableHeader' },
              { text: 'Position', style: 'tableHeader' },
              { text: 'Processed Count', style: 'tableHeader', alignment: 'right' },
            ],
            ...staff_workload.map((w) => [
              { text: w.staff_name || 'Staff Member', style: 'tableCell' },
              { text: w.position || 'Barangay Staff', style: 'tableCell' },
              { text: `${w.processed_count || 0}`, style: 'tableCell', alignment: 'right' },
            ]),
          ],
        },
        layout: 'grid',
      }
    );
  }

  // 6. Detailed Transactions Sample (Up to 100 in PDF for readable formatting)
  const txItems = transactions.items || [];
  if (txItems.length > 0) {
    docDefinition.content.push(
      { text: `Recent Transactions (${Math.min(txItems.length, 50)} of ${transactions.total || txItems.length} records)`, style: 'sectionHeading' }
    );

    if (transactions.truncated) {
      docDefinition.content.push({
        text: `* Notice: Transaction export capped at ${transactions.max_rows || 5000} records due to system export limits.`,
        style: 'warningText',
      });
    }

    docDefinition.content.push({
      table: {
        headerRows: 1,
        widths: [80, 95, 85, 75, 45, 65],
        body: [
          [
            { text: 'Tracking #', style: 'tableHeader' },
            { text: 'Citizen Name', style: 'tableHeader' },
            { text: 'Document', style: 'tableHeader' },
            { text: 'Status', style: 'tableHeader' },
            { text: 'Fee', style: 'tableHeader', alignment: 'right' },
            { text: 'Date', style: 'tableHeader' },
          ],
          ...txItems.slice(0, 50).map((t) => [
            { text: t.tracking_number || '', style: 'tableCell' },
            { text: t.citizen_name || '', style: 'tableCell' },
            { text: t.document_type_name || '', style: 'tableCell' },
            { text: (t.status || '').toUpperCase().replace(/_/g, ' '), style: 'tableCell' },
            { text: `₱ ${(t.fee || 0).toFixed(2)}`, style: 'tableCell', alignment: 'right' },
            { text: t.created_at ? new Date(t.created_at).toISOString().slice(0, 10) : '', style: 'tableCell' },
          ]),
        ],
      },
      layout: 'grid',
    });
  }

  const pdfDoc = pdfmake.createPdf(docDefinition);
  return await pdfDoc.getBuffer();
}

module.exports = {
  generatePdfReport,
};
