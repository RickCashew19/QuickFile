const path = require('path');
const pdfmake = require('pdfmake');
const { config } = require('../../../config');
const { formatLocalTimestamp, formatLocalDate } = require('../../../utils/dateUtil');

// Initialize Roboto fonts from pdfmake package
pdfmake.fonts = {
  Roboto: {
    normal: path.resolve(__dirname, '../../../../node_modules/pdfmake/fonts/Roboto/Roboto-Regular.ttf'),
    bold: path.resolve(__dirname, '../../../../node_modules/pdfmake/fonts/Roboto/Roboto-Medium.ttf'),
    italics: path.resolve(__dirname, '../../../../node_modules/pdfmake/fonts/Roboto/Roboto-Italic.ttf'),
    bolditalics: path.resolve(__dirname, '../../../../node_modules/pdfmake/fonts/Roboto/Roboto-MediumItalic.ttf'),
  },
};

pdfmake.setUrlAccessPolicy(() => false);
pdfmake.setLocalAccessPolicy(() => true);

/**
 * Generates an official PDF report buffer using pdfmake
 * Features repeating headers/footers, dynamic landscape transactions, and signature blocks.
 */
async function generatePdfReport(reportData, options = {}) {
  const { scope = 'staff', actorUser = {} } = options;
  const { summary, by_document_type = [], by_status = [], staff_workload = [], transactions = {}, signatories = {} } = reportData;

  const barangayName = config.jurisdiction.barangayName() || 'Barangay Local Government Unit';
  const cityMunicipality = config.jurisdiction.cityMunicipality() || '';
  const province = config.jurisdiction.province() || '';
  const jurisdictionText = [cityMunicipality, province].filter(Boolean).join(', ');

  const fromFormatted = summary.from || '';
  const toFormatted = summary.to || '';
  const generatedAt = formatLocalTimestamp(new Date());
  const reportTitle = scope === 'admin'
    ? 'Official Barangay Document & Revenue Management Audit Report'
    : 'Barangay Document Transactions & Issuance Summary Report';

  const docDefinition = {
    pageSize: 'A4',
    pageOrientation: 'portrait',
    pageMargins: [40, 65, 40, 50],
    defaultStyle: {
      font: 'Roboto',
      fontSize: 8.5,
      color: '#1f2937',
    },
    styles: {
      reportMainTitle: { fontSize: 13, bold: true, color: '#1e3a8a', alignment: 'center', margin: [0, 0, 0, 2] },
      reportSubtitle: { fontSize: 9.5, bold: true, color: '#4b5563', alignment: 'center', margin: [0, 0, 0, 4] },
      metaText: { fontSize: 8, color: '#6b7280', alignment: 'center' },
      sectionHeading: { fontSize: 10, bold: true, color: '#1e3a8a', margin: [0, 12, 0, 4] },
      tableHeader: { fontSize: 7.5, bold: true, color: '#ffffff', fillColor: '#1e3a8a' },
      tableCell: { fontSize: 7.5 },
      kpiValue: { fontSize: 12, bold: true, color: '#1e3a8a', alignment: 'center' },
      kpiLabel: { fontSize: 7.5, color: '#4b5563', alignment: 'center' },
      noticeText: { fontSize: 8, italics: true, color: '#b91c1c', margin: [0, 3, 0, 5] },
      sigLabel: { fontSize: 8, bold: true, color: '#374151' },
      sigName: { fontSize: 9, bold: true, color: '#111827', margin: [0, 25, 0, 1] },
      sigTitle: { fontSize: 8, color: '#6b7280' },
    },

    // Repeating running header on every page
    header: function (currentPage, pageCount, pageSize) {
      return {
        margin: [40, 15, 40, 0],
        columns: [
          {
            width: '*',
            text: [
              { text: `${barangayName.toUpperCase()}\n`, bold: true, fontSize: 9, color: '#1e3a8a' },
              { text: jurisdictionText ? `${jurisdictionText}\n` : '', fontSize: 7.5, color: '#4b5563' },
              { text: 'QuickFile Barangay Document Management System', fontSize: 7, color: '#6b7280' },
            ],
            alignment: 'left',
          },
          {
            width: '*',
            text: [
              { text: `${reportTitle}\n`, bold: true, fontSize: 8.5, color: '#1e3a8a' },
              { text: `Reporting Period: ${fromFormatted} to ${toFormatted}`, fontSize: 7.5, color: '#4b5563' },
            ],
            alignment: 'right',
          },
        ],
      };
    },

    // Repeating running footer on every page with page numbers
    footer: function (currentPage, pageCount) {
      return {
        margin: [40, 12, 40, 0],
        columns: [
          {
            width: '*',
            text: `Generated by ${actorUser.full_name || 'Authorized Officer'} (${(actorUser.role || 'staff').toUpperCase()}) on ${generatedAt}`,
            fontSize: 7.5,
            color: '#6b7280',
          },
          {
            width: 'auto',
            text: `Page ${currentPage} of ${pageCount}`,
            alignment: 'right',
            fontSize: 7.5,
            color: '#6b7280',
          },
        ],
      };
    },

    content: [
      // Title Block
      { text: barangayName.toUpperCase(), style: 'reportMainTitle' },
      { text: reportTitle, style: 'reportSubtitle' },
      {
        text: `Reporting Period: ${fromFormatted} to ${toFormatted}  |  Scope: ${scope === 'admin' ? 'Administrator (Full System)' : 'Staff (Operations)'}`,
        style: 'metaText',
        margin: [0, 0, 0, 6],
      },
      { canvas: [{ type: 'line', x1: 0, y1: 0, x2: 515, y2: 0, lineWidth: 1, lineColor: '#cbd5e1' }] },

      // Section 1: Executive Summary KPIs
      { text: '1. Executive Summary', style: 'sectionHeading' },
      {
        table: {
          widths: ['*', '*', '*', '*', '*'],
          body: [
            [
              { text: `${summary.total_requests || 0}`, style: 'kpiValue' },
              { text: `${summary.released_count || 0}`, style: 'kpiValue' },
              { text: `${summary.rejected_count || 0}`, style: 'kpiValue' },
              { text: `₱ ${(summary.total_revenue || 0).toLocaleString('en-PH', { minimumFractionDigits: 2 })}`, style: 'kpiValue' },
              { text: `${summary.waived_count || 0} (₱ ${(summary.waived_amount || 0).toFixed(2)})`, style: 'kpiValue' },
            ],
            [
              { text: 'Total Requests', style: 'kpiLabel' },
              { text: 'Released', style: 'kpiLabel' },
              { text: 'Rejected', style: 'kpiLabel' },
              { text: 'Collected Revenue', style: 'kpiLabel' },
              { text: 'Fees Waived', style: 'kpiLabel' },
            ],
          ],
        },
        layout: 'lightHorizontalLines',
      },

      // Section 2: Breakdown by Document Type
      { text: '2. Requests by Document Type', style: 'sectionHeading' },
      {
        table: {
          headerRows: 1,
          widths: [55, '*', 55, 70, 75],
          body: [
            [
              { text: 'Code', style: 'tableHeader' },
              { text: 'Document Name', style: 'tableHeader' },
              { text: 'Requests', style: 'tableHeader', alignment: 'right' },
              { text: 'Unit Fee', style: 'tableHeader', alignment: 'right' },
              { text: 'Revenue', style: 'tableHeader', alignment: 'right' },
            ],
            ...by_document_type.map((d) => [
              { text: d.document_code || 'N/A', style: 'tableCell' },
              { text: d.document_name || 'Unnamed Document', style: 'tableCell' },
              { text: `${d.count || 0}`, style: 'tableCell', alignment: 'right' },
              { text: `₱ ${(d.unit_fee || 0).toFixed(2)}`, style: 'tableCell', alignment: 'right' },
              { text: `₱ ${(d.collected_amount || 0).toFixed(2)}`, style: 'tableCell', alignment: 'right' },
            ]),
          ],
        },
        layout: 'grid',
      },

      // Section 3: Status Breakdown
      { text: '3. Requests by Processing Status', style: 'sectionHeading' },
      {
        table: {
          headerRows: 1,
          widths: ['*', 100],
          body: [
            [
              { text: 'Processing Status', style: 'tableHeader' },
              { text: 'Total Requests', style: 'tableHeader', alignment: 'right' },
            ],
            ...by_status.map((s) => [
              { text: (s.status || '').toUpperCase().replace(/_/g, ' '), style: 'tableCell' },
              { text: `${s.count || 0}`, style: 'tableCell', alignment: 'right' },
            ]),
          ],
        },
        layout: 'grid',
      },
    ],
  };

  // Section 4: Staff Workload (Admin scope only)
  if (scope === 'admin' && Array.isArray(staff_workload) && staff_workload.length > 0) {
    docDefinition.content.push(
      { text: '4. Staff Processing Workload', style: 'sectionHeading' },
      {
        table: {
          headerRows: 1,
          widths: ['*', 70, '*', 70],
          body: [
            [
              { text: 'Staff Officer Name', style: 'tableHeader' },
              { text: 'Role', style: 'tableHeader' },
              { text: 'Actions Breakdown', style: 'tableHeader' },
              { text: 'Total Actions', style: 'tableHeader', alignment: 'right' },
            ],
            ...staff_workload.map((w) => {
              const breakdownText = Object.entries(w.per_status || {})
                .map(([st, cnt]) => `${st.replace(/_/g, ' ')}: ${cnt}`)
                .join(', ');
              return [
                { text: w.staff_name || 'Staff Member', style: 'tableCell' },
                { text: (w.role || 'staff').toUpperCase(), style: 'tableCell' },
                { text: breakdownText || 'None', style: 'tableCell' },
                { text: `${w.total_actions || 0}`, style: 'tableCell', alignment: 'right' },
              ];
            }),
          ],
        },
        layout: 'grid',
      }
    );
  }

  // Section 5: Transactions Table (In Landscape Orientation)
  const txItems = transactions.items || [];
  if (txItems.length > 0) {
    const sectionNum = scope === 'admin' && staff_workload.length > 0 ? '5' : '4';

    // Page break into Landscape orientation for the wide transaction table
    docDefinition.content.push({
      text: '',
      pageBreak: 'before',
      pageOrientation: 'landscape',
    });

    const isTruncated = transactions.truncated;
    const headerTitleText = isTruncated
      ? `${sectionNum}. Detailed Transactions (Showing first ${txItems.length} of ${transactions.total})`
      : `${sectionNum}. Detailed Transactions (${txItems.length} records)`;

    docDefinition.content.push({ text: headerTitleText, style: 'sectionHeading' });

    if (isTruncated) {
      docDefinition.content.push({
        text: `* Showing first ${txItems.length} of ${transactions.total} records due to system export limits.`,
        style: 'noticeText',
      });
    }

    docDefinition.content.push({
      table: {
        headerRows: 1,
        widths: [85, 110, 100, 75, 45, 55, 65, 65, 55, 55],
        body: [
          [
            { text: 'Tracking #', style: 'tableHeader' },
            { text: 'Applicant Name', style: 'tableHeader' },
            { text: 'Document', style: 'tableHeader' },
            { text: 'Status', style: 'tableHeader' },
            { text: 'Fee', style: 'tableHeader', alignment: 'right' },
            { text: 'Payment', style: 'tableHeader' },
            { text: 'Payment Ref', style: 'tableHeader' },
            { text: 'Waiver Reason', style: 'tableHeader' },
            { text: 'Requested', style: 'tableHeader' },
            { text: 'Released', style: 'tableHeader' },
          ],
          ...txItems.map((t) => [
            { text: t.tracking_number || '', style: 'tableCell' },
            { text: t.applicant_name || '', style: 'tableCell' },
            { text: t.document_name || '', style: 'tableCell' },
            { text: (t.status || '').toUpperCase().replace(/_/g, ' '), style: 'tableCell' },
            { text: `₱ ${(t.fee || 0).toFixed(2)}`, style: 'tableCell', alignment: 'right' },
            { text: (t.payment_status || '').toUpperCase(), style: 'tableCell' },
            { text: t.payment_reference || '', style: 'tableCell' },
            { text: t.waiver_reason || '', style: 'tableCell' },
            { text: t.created_at ? formatLocalDate(t.created_at) : '', style: 'tableCell' },
            { text: t.released_at ? formatLocalDate(t.released_at) : '', style: 'tableCell' },
          ]),
        ],
      },
      layout: 'grid',
    });
  }

  // Signature Block on the last page
  const preparedByName = signatories.prepared_by || actorUser.full_name || 'Authorized Officer';
  const notedByName = (signatories.noted_by || '').trim();

  const sigColumns = [
    {
      width: 250,
      stack: [
        { text: 'Prepared By:', style: 'sigLabel' },
        { text: preparedByName, style: 'sigName' },
        { text: `${(actorUser.role || 'staff').toUpperCase()} - Records Officer`, style: 'sigTitle' },
      ],
    },
  ];

  // Omit noted_by if not configured (never print placeholders!)
  if (notedByName) {
    sigColumns.push({
      width: 250,
      stack: [
        { text: 'Noted By:', style: 'sigLabel' },
        { text: notedByName, style: 'sigName' },
        { text: 'Barangay Authority', style: 'sigTitle' },
      ],
    });
  }

  docDefinition.content.push({
    margin: [0, 25, 0, 0],
    columns: sigColumns,
    unbreakable: true,
  });

  const pdfDoc = pdfmake.createPdf(docDefinition);
  return await pdfDoc.getBuffer();
}

module.exports = {
  generatePdfReport,
};